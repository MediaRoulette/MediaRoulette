package dev.mediaroulette.utils.user;

import dev.mediaroulette.domain.user.ImageOptions;
import dev.mediaroulette.model.User;
import dev.mediaroulette.repository.UserRepository;

import java.util.concurrent.ConcurrentHashMap;

public class UserService {
    private final UserRepository userRepository;
    // Bounded LRU cache using Caffeine
    private final com.github.benmanes.caffeine.cache.Cache<String, User> cache = 
            com.github.benmanes.caffeine.cache.Caffeine.newBuilder()
                    .maximumSize(5000)
                    .expireAfterAccess(30, java.util.concurrent.TimeUnit.MINUTES)
                    .build();
    private final java.util.Set<String> dirtyUserIds = java.util.concurrent.ConcurrentHashMap.newKeySet();
    private final java.util.concurrent.ScheduledExecutorService writeScheduler;

    public UserService(UserRepository userRepository) {
        this.userRepository = userRepository;
        this.writeScheduler = java.util.concurrent.Executors.newSingleThreadScheduledExecutor(r -> {
            Thread t = new Thread(r, "UserService-Writer");
            t.setDaemon(true);
            return t;
        });
        this.writeScheduler.scheduleAtFixedRate(this::flushDirtyUsers, 5, 5, java.util.concurrent.TimeUnit.SECONDS);
    }

    /**
     * Fetches an existing user or creates a new one if not found.
     */
    public User getOrCreateUser(String userId) {
        return cache.get(userId, id -> userRepository.findById(id)
                .orElseGet(() -> {
                    User newUser = new User(id);
                    User savedUser = userRepository.save(newUser);
                    
                    // Track new user registration in stats service
                    if (dev.mediaroulette.Main.getStatsService() != null) {
                        dev.mediaroulette.Main.getStatsService().trackNewUser(userId);
                    }
                    
                    return savedUser;
                }));
    }

    /**
     * Checks if a user exists.
     */
    public boolean userExists(String userId) {
        return cache.getIfPresent(userId) != null || userRepository.exists(userId);
    }

    /**
     * Update the user's locale setting.
     */
    public void updateLocale(String userId, String locale) {
        User user = getOrCreateUser(userId);
        user.setLocale(locale);
        updateUser(user);
    }

    /**
     * Generic update method for a user.
     */
    public void updateUser(User user) {
        cache.put(user.getUserId(), user);
        dirtyUserIds.add(user.getUserId());
    }

    // --- Convenience Methods for Updating User Properties ---

    public void incrementImagesGenerated(String userId) {
        User user = getOrCreateUser(userId);
        user.incrementImagesGenerated();
        updateUser(user);
    }

    public void setNsfwEnabled(String userId, boolean enabled) {
        User user = getOrCreateUser(userId);
        user.setNsfw(enabled);
        updateUser(user);
    }

    public void setPremium(String userId, boolean premium) {
        User user = getOrCreateUser(userId);
        user.setPremium(premium);
        updateUser(user);
    }

    public void setAdmin(String userId, boolean admin) {
        User user = getOrCreateUser(userId);
        user.setAdmin(admin);
        updateUser(user);
    }

    public void addFavorite(String userId, String description, String image, String type) {
        // Backward-compatible method
        addFavorite(userId, "Favorite", description, image, type, null);
    }

    public void addFavorite(String userId, String title, String description, String image, String type, Integer accentColor) {
        User user = getOrCreateUser(userId);
        user.addFavorite(title, description, image, type, accentColor);
        updateUser(user);
    }

    public void removeFavorite(String userId, int favoriteId) {
        User user = getOrCreateUser(userId);
        user.removeFavorite(favoriteId);
        updateUser(user);
    }

    public void setChances(String userId, ImageOptions... options) {
        User user = getOrCreateUser(userId);
        user.setChances(options);
        updateUser(user);
    }

    /**
     * Get total number of users in the database
     */
    public long getTotalUsers() {
        return userRepository.getTotalUsers();
    }

    /**
     * Get total images generated by all users
     */
    public long getTotalImagesGenerated() {
        return userRepository.getTotalImagesGenerated();
    }

    // --- Usage Statistics Tracking Methods ---

    /**
     * Track source usage for a user
     */
    public void trackSourceUsage(String userId, String source) {
        User user = getOrCreateUser(userId);
        user.incrementSourceUsage(source);
        updateUser(user);
    }

    /**
     * Track command usage for a user
     */
    public void trackCommandUsage(String userId, String command) {
        User user = getOrCreateUser(userId);
        user.incrementCommandUsage(command);
        updateUser(user);
    }

    /**
     * Add custom subreddit for a user
     */
    public void addCustomSubreddit(String userId, String subreddit) {
        User user = getOrCreateUser(userId);
        user.addCustomSubreddit(subreddit);
        updateUser(user);
    }

    /**
     * Add custom query for a user
     */
    public void addCustomQuery(String userId, String service, String query) {
        User user = getOrCreateUser(userId);
        user.addCustomQuery(service, query);
        updateUser(user);
    }

    /**
     * Update user's last active timestamp
     */
    public void updateLastActive(String userId) {
        User user = getOrCreateUser(userId);
        user.updateLastActive();
        updateUser(user);
    }

    /**
     * Set user's theme
     */
    public void setTheme(String userId, String theme) {
        User user = getOrCreateUser(userId);
        user.setTheme(theme);
        updateUser(user);
    }

    /**
     * Get list of recent user IDs for tab completion.
     * Returns user IDs from the in-memory cache (recently active users).
     */
    public java.util.List<String> getRecentUserIds(int limit) {
        return cache.asMap().keySet().stream()
                .limit(limit)
                .collect(java.util.stream.Collectors.toList());
    }

    public UserRepository getUserRepository() {
        return userRepository;
    }

    private void flushDirtyUsers() {
        if (dirtyUserIds.isEmpty()) return;
        java.util.List<String> idsToFlush = new java.util.ArrayList<>(dirtyUserIds);
        dirtyUserIds.removeAll(idsToFlush);
        for (String id : idsToFlush) {
            User user = cache.getIfPresent(id);
            if (user != null) {
                try {
                    userRepository.save(user);
                } catch (Exception e) {
                    org.slf4j.LoggerFactory.getLogger(UserService.class)
                            .error("Failed to save user {} during flush: {}", id, e.getMessage());
                    dirtyUserIds.add(id); // Retry next time
                }
            }
        }
    }

    public void shutdown() {
        if (writeScheduler != null) {
            writeScheduler.shutdown();
            try {
                if (!writeScheduler.awaitTermination(5, java.util.concurrent.TimeUnit.SECONDS)) {
                    writeScheduler.shutdownNow();
                }
            } catch (InterruptedException e) {
                writeScheduler.shutdownNow();
                Thread.currentThread().interrupt();
            }
        }
        flushDirtyUsers();
    }
}
